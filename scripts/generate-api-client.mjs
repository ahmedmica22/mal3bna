import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

process.chdir(fileURLToPath(new URL('../', import.meta.url)));

const document = JSON.parse(await readFile('apps/api/openapi/openapi.json', 'utf8'));
function typescript(schema) {
  if (schema.$ref) {
    const parts = schema.$ref
      .slice(2)
      .split('/')
      .map((part) => part.replaceAll('~1', '/').replaceAll('~0', '~'));
    if (parts.length === 3 && parts[0] === 'components' && parts[1] === 'schemas') return parts[2];
    const target = parts.reduce((value, part) => value?.[part], document);
    if (!target) throw new Error(`Unresolved OpenAPI reference: ${schema.$ref}`);
    return typescript(target);
  }
  if (Array.isArray(schema.type))
    return schema.type.map((type) => typescript({ ...schema, type })).join(' | ');
  if ('const' in schema) return JSON.stringify(schema.const);
  if (schema.enum) return schema.enum.map((value) => JSON.stringify(value)).join(' | ');
  if (schema.anyOf || schema.oneOf)
    return (schema.anyOf ?? schema.oneOf).map(typescript).join(' | ');
  if (schema.type === 'object')
    return `{ ${Object.entries(schema.properties ?? {})
      .map(
        ([key, value]) =>
          `${JSON.stringify(key)}${schema.required?.includes(key) ? '' : '?'}: ${typescript(value)}`,
      )
      .join('; ')} }`;
  if (schema.type === 'array') return `Array<${typescript(schema.items)}>`;
  if (schema.type === 'integer' || schema.type === 'number') return 'number';
  if (['string', 'boolean', 'null'].includes(schema.type)) return schema.type;
  return 'unknown';
}
const types = Object.entries(document.components?.schemas ?? {})
  .map(([name, schema]) => `export type ${name} = ${typescript(schema)};`)
  .join('\n');
const paths = Object.entries(document.paths ?? {}).flatMap(([path, operations]) =>
  Object.keys(operations)
    .filter((method) =>
      ['get', 'post', 'put', 'patch', 'delete', 'head', 'options', 'trace'].includes(method),
    )
    .map((method) => `${method.toUpperCase()} ${path}`),
);
const source = `// Generated by scripts/generate-api-client.mjs. Do not edit.\n\nexport type ApiRoute = ${paths.map((path) => JSON.stringify(path)).join(' | ') || 'never'};\n\nexport { GeneratedApiClient, ApiError, type ApiClientOptions } from './transport.js';\nexport { SessionClient, type SessionClientOptions } from './session-client.js';\n`;
await mkdir('packages/api-client/src', { recursive: true });
const output = 'packages/api-client/src/generated.ts';
await writeFile(output, `${source}\n${types}\n`);
execFileSync(process.execPath, ['node_modules/prettier/bin/prettier.cjs', '--write', output], {
  stdio: 'ignore',
});
console.log(`Generated typed client metadata for ${paths.length} routes`);
