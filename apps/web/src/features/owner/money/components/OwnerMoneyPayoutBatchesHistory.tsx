import { Receipt } from 'lucide-react';
import type { OwnerMoneyContentProps } from '../types';

export function OwnerMoneyPayoutBatchesHistory({
  locale,
  payoutList,
  translate,
}: Pick<OwnerMoneyContentProps, 'locale' | 'payoutList' | 'translate'>) {
  return (
    <div className="space-y-4">
      <h2 className="text-xl font-black text-slate-900 dark:text-slate-100">
        {translate('Payout Batches & History')}
      </h2>
      {payoutList.length === 0 ? (
        <div className="rounded-3xl border border-slate-200 bg-white p-8 text-center shadow-lg dark:border-white/10 dark:bg-[#13221f]/70 max-w-lg mx-auto space-y-3">
          <div className="w-12 h-12 rounded-2xl bg-emerald-500/10 text-emerald-700 dark:bg-lime-400/10 dark:text-lime-400 flex items-center justify-center mx-auto">
            <Receipt size={24} />
          </div>
          <h3 className="text-base font-black text-slate-900 dark:text-slate-100 m-0">
            {translate('No payouts generated yet.')}
          </h3>
          <p className="text-xs text-slate-500 dark:text-slate-400 max-w-sm mx-auto leading-relaxed m-0">
            {translate(
              'Platform payouts are batch-generated by admin and sent directly via bank transfer or InstaPay.',
            )}
          </p>
        </div>
      ) : (
        <div className="rounded-3xl border border-slate-200 bg-slate-50 shadow-2xl backdrop-blur-md overflow-x-auto dark:border-white/10 dark:bg-[#0b1715]/90">
          <table className="w-full border-collapse min-w-[650px]">
            <thead>
              <tr className="border-b border-slate-200 text-start text-xs font-black text-emerald-700 uppercase tracking-wider dark:border-white/10 dark:text-lime-400">
                <th className="p-4">{translate('Payout ID')}</th>
                <th className="p-4">{translate('Billing Period')}</th>
                <th className="p-4">{translate('Amount')}</th>
                <th className="p-4">{translate('Status')}</th>
                <th className="p-4">{translate('Payment Reference')}</th>
              </tr>
            </thead>
            <tbody className="divide-y divide-white/5 text-xs">
              {payoutList.map((p) => (
                <tr key={p.id} className="hover:bg-white/[0.02] transition-colors">
                  <td className="p-4">
                    <span className="font-mono font-bold text-slate-600 dark:text-slate-300">
                      #{p.id.slice(0, 8)}
                    </span>
                  </td>
                  <td className="p-4 text-slate-600 font-medium dark:text-slate-300">
                    {new Date(p.periodStart).toLocaleDateString(locale, {
                      timeZone: 'Africa/Cairo',
                    })}{' '}
                    -{' '}
                    {new Date(p.periodEnd).toLocaleDateString(locale, {
                      timeZone: 'Africa/Cairo',
                    })}
                  </td>
                  <td className="p-4">
                    <strong className="text-emerald-700 font-bold text-sm dark:text-lime-400">
                      {(p.amountPiastres / 100).toFixed(2)} {translate('EGP')}
                    </strong>
                  </td>
                  <td className="p-4">
                    <span
                      className={`inline-flex px-2.5 py-1 rounded-full text-[11px] font-bold border capitalize ${
                        p.status === 'paid'
                          ? 'bg-emerald-500/15 border-emerald-500/30 text-emerald-700 dark:text-emerald-400'
                          : p.status === 'approved'
                            ? 'bg-sky-500/15 border-sky-500/30 text-sky-700 dark:text-sky-400'
                            : 'bg-amber-500/15 border-amber-500/30 text-amber-800 dark:text-amber-400'
                      }`}
                    >
                      {translate(p.status)}
                    </span>
                  </td>
                  <td className="p-4 text-slate-500 font-medium dark:text-slate-400">
                    {p.paymentReference ?? translate('Pending transfer')}
                  </td>
                </tr>
              ))}
            </tbody>
          </table>
        </div>
      )}
    </div>
  );
}
